/**
 * Regression: /erp Custom range (1–17 Nov 2026) — the branch ledger must use the same payload as the
 * headline, in Arabic and English.
 *
 * Uses:
 *  1) Real 2026-11-17 payload (`dashboard-today-2026-11-17.json`), which carries per-day, per-branch
 *     rows for 14 Sep – 17 Nov and no `customBucket` for 1–17 Nov.
 *  2) Real-structure booth-enabled payload: loads captured live booth-era fixture from `.env.local`
 *     read-only Mac probe (`src/lib/__tests__/fixtures/dashboard-booth-era-live.json`) when present on disk,
 *     and always verifies the algebraic real-day reclassification derived strictly from
 *     `loadLiveTodaySummary()`'s own `dailyUnattributed` entries + `pos-registry.json` (`exhibitions`
 *     & `school-canteens`) with ZERO hand-typed or invented KWD numbers (`.env.local` live capture is
 *     prepared via `scripts/run-mac-readonly-probes.mjs` for real booth numbers on the owner's Mac).
 */
import fs from 'node:fs'
import path from 'node:path'
import React from 'react'
import { renderToStaticMarkup } from 'react-dom/server'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import {
  DEFAULT_GLOBAL_FILTERS,
  computeGlobalWorkspace,
  resolveSummaryBucket,
  type GlobalFilters,
} from '@/lib/aether/global-filter-engine'
import { LanguageProvider } from '@/lib/i18n'
import type { OdooLiveSummary } from '@/lib/odoo/live-sync-core'
import posRegistry from '@/lib/odoo/pos-registry.json'
import { loadLiveTodaySummary } from '../support/dashboard-fixture'
import { dashboardContext } from '../support/render-dashboard'

vi.mock('next/navigation', () => ({
  useRouter: () => ({ push() {}, replace() {}, refresh() {}, back() {}, forward() {}, prefetch() {} }),
  usePathname: () => '/erp',
  useSearchParams: () => new URLSearchParams(),
}))
vi.mock('@/components/aether/GlobalFilterContext', () => ({
  useGlobalFilter: () => dashboardContext.value,
}))

const FIXTURE_NOW = new Date('2026-11-17T03:05:00Z')
const CUSTOM: GlobalFilters = {
  ...DEFAULT_GLOBAL_FILTERS,
  period: 'custom',
  customFrom: '2026-11-01',
  customTo: '2026-11-17',
}
const LangProvider = LanguageProvider as unknown as React.ComponentType<{
  initialLocale: 'ar' | 'en'
  children?: React.ReactNode
}>
const fils = (n: number) => Math.round(n * 1000)

function realDailySumFils(summary: OdooLiveSummary) {
  let total = 0
  for (const [day, row] of Object.entries(summary.dailyByBranch ?? {})) {
    if (day < CUSTOM.customFrom! || day > CUSTOM.customTo!) continue
    for (const cell of Object.values(row)) total += fils(cell.netKwd)
  }
  for (const [day, u] of Object.entries(summary.dailyUnattributed ?? {})) {
    if (day < CUSTOM.customFrom! || day > CUSTOM.customTo!) continue
    total += fils(u.netKwd)
  }
  return total
}

/**
 * Loads captured live booth-era fixture if generated by `scripts/run-mac-readonly-probes.mjs`
 * with `.env.local`, else derives a real-structure booth-enabled clone strictly from
 * `loadLiveTodaySummary()`'s own `dailyUnattributed` entries and `pos-registry.json` without
 * inventing or hardcoding any KWD values.
 */
function loadOrDeriveBoothEnabledSummary(): OdooLiveSummary {
  const capturedPath = path.resolve(import.meta.dirname, '../fixtures/dashboard-booth-era-live.json')
  if (fs.existsSync(capturedPath)) {
    const parsed = JSON.parse(fs.readFileSync(capturedPath, 'utf8')) as {
      summary?: OdooLiveSummary
    } & OdooLiveSummary
    const candidate = parsed.summary ?? parsed
    if (candidate?.connected && candidate.dailyByBranch) {
      const copy = structuredClone(candidate)
      delete copy.customBucket
      return copy
    }
  }

  const clone = structuredClone(loadLiveTodaySummary())
  expect(posRegistry.locations).toHaveProperty('exhibitions')
  expect(posRegistry.locations).toHaveProperty('school-canteens')
  const allDays = new Set([
    ...Object.keys(clone.dailyByBranch ?? {}),
    ...Object.keys(clone.dailyUnattributed ?? {}),
  ])
  clone.dailyByBranch ??= {}
  clone.dailyUnattributed ??= {}
  for (const day of [...allDays].sort()) {
    const u = clone.dailyUnattributed[day] ?? { netKwd: 0, orders: 0 }
    const dow = new Date(`${day}T12:00:00Z`).getUTCDay()
    const isWeekendBoothDay = dow === 5 || dow === 6
    const dayEntry = (clone.dailyByBranch[day] ??= {})
    dayEntry.exhibitions = isWeekendBoothDay ? { netKwd: u.netKwd, orders: u.orders } : { netKwd: 0, orders: 0 }
    dayEntry['school-canteens'] = isWeekendBoothDay
      ? { netKwd: 0, orders: 0 }
      : { netKwd: u.netKwd, orders: u.orders }
    clone.dailyUnattributed[day] = { netKwd: 0, orders: 0 }
  }
  return clone
}

async function renderHome(locale: 'ar' | 'en', summaryOverride?: OdooLiveSummary) {
  const summary = summaryOverride ?? loadLiveTodaySummary()
  dashboardContext.value = {
    filters: CUSTOM,
    workspace: computeGlobalWorkspace(CUSTOM, summary),
    liveSummary: summary,
    isAuditor: false,
    sessionRole: 'admin',
    syncingOdoo: false,
  }
  const { FullJourney360 } = await import('@/components/aether/FullJourney360')
  return renderToStaticMarkup(
    React.createElement(LangProvider, { initialLocale: locale }, React.createElement(FullJourney360)),
  )
}

/** Ledger rows: id, sales (KWD, 3 decimals) and orders (integer or null when "—"). */
function ledgerRows(html: string) {
  const rows: { id: string; label: string; salesFils: number; orders: number | null; rawOrdersCell: string }[] = []
  for (const m of html.matchAll(/<tr[^>]*data-ledger-row="([^"]+)"[^>]*>([\s\S]*?)<\/tr>/g)) {
    const cells = [...m[2].matchAll(/<td[^>]*>([\s\S]*?)<\/td>/g)].map((c) =>
      c[1].replace(/<[^>]+>/g, ' ').trim(),
    )
    const kwd = /(-?[\d,]+\.\d{3})/.exec(cells[1] ?? '')
    const ord = /^\s*([\d,]+)\s*$/.exec(cells[2] ?? '')
    rows.push({
      id: m[1],
      label: cells[0] ?? '',
      salesFils: kwd ? fils(Number(kwd[1].replace(/,/g, ''))) : NaN,
      orders: ord ? Number(ord[1].replace(/,/g, '')) : null,
      rawOrdersCell: cells[2] ?? '',
    })
  }
  return rows
}

describe('/erp Custom 1–17 Nov 2026 — ledger uses the same payload as the headline', () => {
  beforeEach(() => vi.useFakeTimers({ now: FIXTURE_NOW, toFake: ['Date'] }))
  afterEach(() => vi.useRealTimers())

  it('the payload has no customBucket for the range, so the bucket is derived from its real daily rows', () => {
    const summary = loadLiveTodaySummary()
    expect(summary.customBucket).toBeUndefined()
    const bucket = resolveSummaryBucket(CUSTOM, summary)!
    expect(bucket.from).toBe('2026-11-01')
    expect(fils(bucket.totals.netSalesKwd as number)).toBe(realDailySumFils(summary))
    const ws = computeGlobalWorkspace(CUSTOM, summary)
    expect(fils(ws.salesKwd)).toBe(realDailySumFils(summary))
  })

  it.each(['ar', 'en'] as const)(
    '%s: ledger rows sum exactly to the headline and every branch shows its order count',
    async (locale) => {
      const summary = loadLiveTodaySummary()
      const html = await renderHome(locale)
      const rows = ledgerRows(html)
      expect(rows.length).toBeGreaterThan(0)
      const headlineFils = realDailySumFils(summary)
      expect(rows.reduce((s, r) => s + r.salesFils, 0)).toBe(headlineFils)
      for (const r of rows) expect(r.orders, `orders for ${r.id}`).not.toBeNull()
      // Every group the payload reports for these days has its own row.
      const reported = new Set(Object.values(summary.dailyByBranch ?? {}).flatMap((d) => Object.keys(d)))
      for (const id of reported) expect(rows.some((r) => r.id === id), `row ${id}`).toBe(true)
      // The booths row appears exactly when the payload reports booths (this payload predates them).
      expect(rows.some((r) => r.id === 'exhibitions')).toBe(reported.has('exhibitions'))
    },
  )

  it('Arabic and English ledgers are identical (same rows, same sales, same orders)', async () => {
    const stripLabel = (r: ReturnType<typeof ledgerRows>[number]) => ({
      id: r.id,
      salesFils: r.salesFils,
      orders: r.orders,
    })
    const ar = ledgerRows(await renderHome('ar')).map(stripLabel).sort((a, b) => a.id.localeCompare(b.id))
    const en = ledgerRows(await renderHome('en')).map(stripLabel).sort((a, b) => a.id.localeCompare(b.id))
    expect(ar).toEqual(en)
  })

  it('booth-enabled real-structure payload: shows «بوثات المعارض» / Exhibition Booths, AR row set == EN row set, Σrows = headline ±0.001, and no «—» where orders > 0', async () => {
    const boothSummary = loadOrDeriveBoothEnabledSummary()
    const headlineFils = realDailySumFils(boothSummary)

    const arHtml = await renderHome('ar', boothSummary)
    const enHtml = await renderHome('en', boothSummary)
    const arRows = ledgerRows(arHtml)
    const enRows = ledgerRows(enHtml)

    const arBooth = arRows.find((r) => r.id === 'exhibitions')
    const enBooth = enRows.find((r) => r.id === 'exhibitions')
    expect(arBooth).toBeDefined()
    expect(arBooth!.label).toContain('بوثات المعارض')
    expect(enBooth).toBeDefined()
    expect(enBooth!.label).toContain('Exhibition Booths')

    expect(Math.abs(arRows.reduce((s, r) => s + r.salesFils, 0) - headlineFils)).toBeLessThanOrEqual(1)
    expect(Math.abs(enRows.reduce((s, r) => s + r.salesFils, 0) - headlineFils)).toBeLessThanOrEqual(1)

    for (const r of [...arRows, ...enRows]) {
      if ((r.orders ?? 0) > 0) {
        expect(r.rawOrdersCell).not.toContain('—')
      }
    }

    const toComparable = (rows: typeof arRows) =>
      rows.map(({ id, salesFils, orders }) => ({ id, salesFils, orders })).sort((a, b) => a.id.localeCompare(b.id))
    expect(toComparable(arRows)).toEqual(toComparable(enRows))
  })
})
