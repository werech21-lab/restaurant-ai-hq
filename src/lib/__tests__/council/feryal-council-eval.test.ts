/**
 * Feryal executive eval — 12 questions (factual, strategic, cross-domain, Gulf dialect).
 *
 * Real data only: the live 17 Nov 2026 payload (06:05 Kuwait sync) for the Odoo numbers, and the
 * advisor council run on that payload plus the real 31 Oct 2026 Odoo export (attendance, stock).
 * Her actual answers are written to docs/phase-5/feryal-council-eval.md for the report.
 */
import fs from 'node:fs'
import path from 'node:path'
import { beforeAll, beforeEach, describe, expect, it } from 'vitest'
import { askFeryalOdooAgent, resetFeryalAuditCache, verifyFeryalReplyNumbers, type AskFeryalOdooAgentResult } from '@/lib/feryal-odoo-agent'
import { SUGGESTED_SEASON_EVENTS } from '@/lib/council/advisors/seasons'
import { runCouncil } from '@/lib/council/runner'
import type { CouncilSnapshot } from '@/lib/council/types'
import { buildAdvisoryBlock } from '@/lib/feryal/advisor-synthesis'
import { createRealPayloadDataSource, REAL_SYNC_NOW_MS } from './feryal-real-source'
import { loadLiveTodaySummary, realHrInput, realInventoryInput } from './support'

interface EvalQ {
  id: string
  kind: 'factual' | 'strategic' | 'cross-domain' | 'dialect'
  question: string
  /** The reply must carry the advisory why / proposals block. */
  expectsAdvice: boolean
}

export const EVAL_QUESTIONS: EvalQ[] = [
  { id: 'Q1', kind: 'factual', question: 'كم كانت مبيعات أمس؟', expectsAdvice: true },
  { id: 'Q2', kind: 'dialect', question: 'شلون كانت العاصمة امبارح؟', expectsAdvice: true },
  { id: 'Q3', kind: 'factual', question: 'أي فرع الأعلى مبيعات أمس؟', expectsAdvice: true },
  { id: 'Q4', kind: 'dialect', question: 'شو صاير بالأفنيوز؟ كم بعنا امس', expectsAdvice: true },
  { id: 'Q5', kind: 'strategic', question: 'شنو أسوي عشان أرفع المبيعات هالأسبوع؟', expectsAdvice: true },
  { id: 'Q6', kind: 'cross-domain', question: 'ليش العاصمة نازلة؟ هل السبب الطاقم ولا المنصات؟', expectsAdvice: true },
  { id: 'Q7', kind: 'strategic', question: 'طلبات توقف عندنا وايد، شنو الحل؟', expectsAdvice: true },
  { id: 'Q8', kind: 'cross-domain', question: 'الأوفر تايم عند الموظفين واجد، شنو تقترحين؟', expectsAdvice: true },
  { id: 'Q9', kind: 'strategic', question: 'وين نخسر بالمخزون؟', expectsAdvice: true },
  { id: 'Q10', kind: 'strategic', question: 'أيام الرواتب قربت، شلون نتجهز؟', expectsAdvice: true },
  { id: 'Q11', kind: 'dialect', question: 'العارضية يوم الجمعة شلون مقارنة بالفروع الثانية؟', expectsAdvice: true },
  { id: 'Q12', kind: 'factual', question: 'كم مبيعات القرين المطبخ المركزي هالشهر؟', expectsAdvice: false },
]

let council: CouncilSnapshot
const answers = new Map<string, AskFeryalOdooAgentResult>()

beforeAll(() => {
  const s = loadLiveTodaySummary()
  council = runCouncil({ cfo: { summary: s }, hr: realHrInput(), inventory: realInventoryInput(), seasons: { summary: s, events: SUGGESTED_SEASON_EVENTS } })
})

describe('Feryal — 12 executive eval questions on real data', () => {
  beforeEach(() => resetFeryalAuditCache())

  it.each(EVAL_QUESTIONS)('$id ($kind): $question', async (q) => {
    const res = await askFeryalOdooAgent({
      question: q.question,
      userSub: 'council-eval',
      userRole: 'gm',
      referenceNowMs: REAL_SYNC_NOW_MS,
      dataSource: createRealPayloadDataSource(loadLiveTodaySummary()),
      skipAuditLog: true,
      council,
    })
    answers.set(q.id, res)
    // Never a fake zero, never an untraced number in the base answer.
    expect(res.reply).not.toMatch(/(?:^|[^\d.,])0\.000(?!\d)/)
    if (res.status === 'answered') expect(res.verifier.valid, res.reply).toBe(true)
    if (q.expectsAdvice) {
      expect(res.advisory?.findings.length ?? 0, res.reply).toBeGreaterThan(0)
      expect(res.reply).toMatch(/• (?:لماذا|غير متوفر في Odoo):/)
      expect(res.reply).toContain('• مصادر المستشارين:')
    }
    // Every numeric advisor Estimate («تقدير: value») carries its formula.
    for (const line of res.reply.split('\n').filter((l) => l.includes('تقدير:'))) expect(line).toMatch(/تقدير: .+ = .+/)
  })

  it('writes the actual answers to docs/phase-5/feryal-council-eval.md', () => {
    const md = [
      '# Feryal — 12 executive eval answers (real data)',
      '',
      'Odoo numbers: live payload synced 2026-11-17 06:05 Asia/Kuwait. Advisors: that payload + the real Odoo export of 2026-10-31 (hr.attendance, stock.quant; 1000-row cap). Generated by `src/lib/__tests__/council/feryal-council-eval.test.ts`.',
      '',
      ...EVAL_QUESTIONS.flatMap((q) => {
        const a = answers.get(q.id)
        return [`## ${q.id} · ${q.kind}`, '', `**${q.question}**`, '', `status: \`${a?.status}\` · advisors: ${a?.advisory?.advisors.join(', ') || '—'}`, '', '```text', a?.reply ?? '(no answer)', '```', '']
      }),
    ].join('\n')
    const out = path.join(process.cwd(), 'docs', 'phase-5', 'feryal-council-eval.md')
    fs.mkdirSync(path.dirname(out), { recursive: true })
    fs.writeFileSync(out, md)
    expect(answers.size).toBe(12)
  })
})

describe('number guard', () => {
  it('drops a proposal whose figure does not trace to a report, and keeps the rest', () => {
    const tampered: CouncilSnapshot = JSON.parse(JSON.stringify(council))
    const f = tampered.reports.flatMap((r) => r.findings).find((x) => x.fingerprint.startsWith('cfo:wow-divergence'))!
    // Inject an untraceable figure into one proposal's text.
    f.proposals[0].what.ar = `${f.proposals[0].what.ar} لرفع المبيعات 4242.5 د.ك`
    const block = buildAdvisoryBlock({ question: 'ليش العاصمة نازلة؟', branchId: 'assima', council: tampered }, (t, allowed, opts) => verifyFeryalReplyNumbers(t, allowed, opts))
    expect(block).not.toBeNull()
    expect(block!.text).not.toContain('4242.5')
    expect(block!.text).toContain(f.proposals[1].what.ar)
  })

  it('adds nothing when no council snapshot is available', () => {
    expect(buildAdvisoryBlock({ question: 'كم مبيعات أمس؟', council: null }, (t, a, o) => verifyFeryalReplyNumbers(t, a, o))).toBeNull()
  })
})
