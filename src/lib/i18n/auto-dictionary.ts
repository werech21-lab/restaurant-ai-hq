/** Sorted once for longest-match phrase replacement. */
export const AR_TO_EN_ENTRIES: Array<[string, string]> = Object.entries(AR_TO_EN).sort(
  (a, b) => b[0].length - a[0].length,
)

export const ARABIC_RE = /[\u0600-\u06FF]/

export function translateArabicText(raw: string): string {
  const text = raw.trim()
  if (!text || !ARABIC_RE.test(text)) return raw
  if (AR_TO_EN[text]) {
    const leading = raw.match(/^\s*/)?.[0] ?? ''
    const trailing = raw.match(/\s*$/)?.[0] ?? ''
    return `${leading}${AR_TO_EN[text]}${trailing}`
  }
  let out = raw
  for (const [ar, en] of AR_TO_EN_ENTRIES) {
    if (out.includes(ar)) out = out.split(ar).join(en)
  }
  return out
}
