export type DeliveryZoneStatus =
  | 'ONLINE_VISIBLE'     // 🟢 ظاهر ومتاح للطلب (Normal Talabat Go Delivery)
  | 'BUSY_IN_AREA'       // 🟡 يظهر للعميل "مشغول / Busy" في هذه المنطقة
  | 'AREA_CLOSED_HIDDEN' // 🔴 المنطقة مقطوعة / المطعم مخفي (Polygon Shrunk by Talabat)
  | 'FORCED_TGO_17'      // 🟠 تحول قسري من توصيل المطعم TMP 10% إلى TGO 17%

export type IncidentRootCause =
  | 'TALABAT_FLEET_SHORTAGE' // نقص سائقي طلبات في المنطقة (Talabat Fleet Shortage)
  | 'PEAK_RADIUS_CUT'        // تقليص نطاق التوصيل وقت الذروة (Peak Radius Cut from 6km to 2.5km)
  | 'HIGH_KITCHEN_LOAD'      // ضغط تحضير المطبخ (High Kitchen Load)
  | 'MANUAL_TABLET_STOP'     // إيقاف يدوي من التابلت (Manual Tablet Stop)

