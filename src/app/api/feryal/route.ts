import { FERYAL_VENTURE_FOODS_KNOWLEDGE, getDeterministicFeryalReply } from '@/lib/feryal-gemini-brain'
import { ODOO } from '@/lib/odoo/odoo-dataset'

export const runtime = 'nodejs'
export const dynamic = 'force-dynamic'

const n3 = (n: number) => n.toLocaleString('en-US', { minimumFractionDigits: 3, maximumFractionDigits: 3 })
const n0 = (n: number) => n.toLocaleString('en-US', { maximumFractionDigits: 0 })
const channelOf = (id: string) => CHANNELS.find((c) => c.id === id)
const TOP_PROFIT = [...BRANCHES].sort((a, b) => b.profit - a.profit)[0]

// Live Odoo master data (whitelisted POS registers, generated by scripts/sync-odoo-live.mjs)
