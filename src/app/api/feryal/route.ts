import { NextRequest, NextResponse } from 'next/server'
import { getOpenAIApiKey } from '@/lib/openai-key'
import { BRANCHES, CHANNELS, LEDGER, LEVERS_MONTHLY_TOTAL } from '@/lib/aether/ledger'
